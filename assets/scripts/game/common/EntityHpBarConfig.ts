/**
 * ============================================================
 * EntityHpBarConfig —— 单位血条的数值口径（唯一数据源）
 * ============================================================
 *
 * 与 EntityVisualConfig / DamageTextConfig 同一条约定：本文件**不依赖 cc**
 * （只存数值与字符串），表现层（entityview/HpBar.ts）负责把它落到节点上。
 *
 * 血条的三个量各自的来源：
 *   长度 —— **预制件里 hp_bar 摆的宽度**（当前 20，正好等于单位身体宽度）。
 *           运行时按生命百分比缩短它（锚点在左，所以从左往右掉）→
 *           想改血条长度就在编辑器里改预制件，代码不用动。
 *   高度 —— 本表 `worldHeight` **定死**（见下，需求口径）
 *   时长 —— 本表 `hideDelay`（未受击多久后隐藏）
 *
 * 另有打击反馈 B3（F6）的**延迟条/残影条**一组数（`lag*`，见下）——
 * 它同样属于"血条"这一个东西，所以放在本表而不是 `HitFeelConfig`（一个东西只有一个数值源）。
 */
export const HP_BAR = {
    /** 预制件里血条节点的名字（EntityView 在自己的子节点里按此名字查找） */
    nodeName: 'hp_bar',

    /**
     * 未受击多久后自动隐藏（秒）—— 需求：2s
     *
     * 每次受击都**重新计时**：连击/DoT 期间血条一直亮着，停手 2s 才收。
     */
    hideDelay: 2,

    /**
     * 血条的**世界高度**（定死，不随父预制件缩放变化）—— 需求：只有 5
     *
     * 为什么必须定死：血条挂在**单位预制件根节点**下，而根节点的缩放是按体型给的
     * （见 EntityVisualConfig：普通 ×1 / 精英 ×1.3 / 经济·击杀·阶段 Boss ×1.5 / 最终 Boss ×2）。
     * 直接继承父缩放的话，最终 Boss 的血条会变成 5×2 = 10 单位粗 —— 又胖又抢戏。
     * 实现：HpBar 把自己的 scale.y 设成 1/父节点世界缩放，世界高度于是恒等于本值。
     *
     * 注意：本值会覆盖预制件里 hp_bar 的摆位高度（预制件当前也是 5，两者一致）。
     */
    worldHeight: 5,

    /* ===== 延迟条（打击反馈 B3 / F6：「血条先掉、残影条慢慢跟上」）===== */

    /**
     * 延迟条节点名 —— 运行时在**单位根节点**下创建，并**插在 hp_bar 之前**（= 画在血条下面）。
     *
     * 为什么必须是兄弟节点而不是 hp_bar 的子节点：Cocos 的绘制顺序是"父节点自己的 Sprite
     * 先画、子节点后画"，挂在 hp_bar 下面的话残影条会**盖在血条上**（正好反了 ——
     * 残影条要表达的是"已经掉掉的那一段"，必须被血条压在后面）。
     */
    lagNodeName: 'hp_lag',

    /**
     * 残影条追上真实血条的时长（秒）—— 设计要求 0.6s。
     *
     * 曲线是 **ease-out（先快后慢）**：掉血那一刻残影条迅速收掉大半、末段慢慢贴上去，
     * 读起来是"这一下打掉了一大截"，而不是"有条东西在匀速飘"。
     */
    lagSec: 0.6,

    /**
     * 残影条颜色与不透明度（0xRRGGBB + 0~1）。
     *
     * **为什么是墨色而不是白色的"残影"**：血条本体是红 `#F52121`、战场底是 `#EBF4FB`（近白）——
     * 白色残影条在这种底色上等于没画。墨色 α0.45 在浅底上压成冷灰，
     * 与红条**明度与色相都不同**，一眼分得出"这是已经掉掉的那一段"。
     */
    lagColor: 0x14181b,
    lagAlpha: 0.45,
} as const;
