/**
 * ============================================================
 * BossStrengthConfig —— 阶段 Boss / 最终 Boss 的**强度曲线**唯一数值真源（纯 TS，无 cc 依赖）
 * ============================================================
 *
 * 「Boss 太弱」这件事的根因不是某一行的数字写小了，而是**两只 Boss 共用同一行配置、
 * 且强度完全不随局内成长走**：
 *   · `Scene_Game_Stage.defaultConfig` 里 `stageBossUnitId === finalBossUnitId === 2006`，
 *     阶段 Boss 与最终 Boss 只有**表现缩放**不同（×1.5 / ×2），属性一模一样（HP 3000）。
 *   · 玩家的局内成长（遗物 + 等级）在 960 秒里把面板 DPS 抬了 **5~6 倍**，
 *     而 Boss 的血一直没动 ⇒ 越到后期 Boss 越像纸糊的：
 *     实测中位英雄墙钟 TTK = 阶段 Boss#1 **60s** → #2 **41s** → #3 **22s** → 最终 Boss **13s**
 *     （普攻型英雄更快：最终 Boss 只扛 **12s**，最快的英雄 **8s**）。
 *
 * ── 本文件负责什么 ──
 *   只回答一个问题：「**这一次刷出来的 Boss，血量与攻击该乘多少**」。
 *   难度档位那一层（`1.12^(N-1)`）仍归 `DifficultyConfig.bossHpMul`，两者**相乘、互不覆盖**。
 *
 * ── 为什么是"倍率曲线"而不是改 `units.json` ──
 *   ① 阶段 Boss 与最终 Boss **本来就是同一行配置**（同一个 2006，同一只深渊领主）；
 *      要在表里分开就得凭空多一行「同一只怪的第二份数值」，而它连美术都是复用的。
 *   ② 这条曲线是**模式规则**（哪个刷新点该给多强），与 `DifficultyConfig` / `StageTimingConfig`
 *      同一性质 —— 项目里这类"曲线常量"一律放纯 TS 真源，改表改不动的就放这里。
 *   ③ ⚠ **不能**把它塞进 `applyDifficultyScale`（那个 hook 只认 `UnitKind`）：
 *      玩家自己放的「敌方守卫」（units.json#2010，`rewardType: 'boss'`）解析出来**也是 StageBoss**，
 *      按 kind 加成就把玩家的工具怪一起变肉了。所以它落在**刷新点** `Scene_Game_Stage.spawnBoss`。
 *
 * ── 目标（用户口径 2026-11）──
 *   最终 Boss = **30 秒定标 × 取 75% ⇒ 40 秒**（在「**最高成长**」那一档上，
 *   即"局外每件 3 份 + 满成就 + 全清 + 平衡挑牌 + 神器买满"）。
 *   且**四只 Boss 都要有收官战的分量**（不是越打越快）。
 *   ⚠ **2026-11 追加的第二条口径：低难度那一侧要"过得去"** —— 用户实测「难度 1 打不过」，
 *   于是阶段 1/2 的强度被砍到 ×0.25 / ×0.8（见 `STAGE_BOSS_HP_MUL`）。
 *   两条口径的**服务对象不同**：40 秒那条管的是**高难度下的最高成长玩家**，
 *   ×0.25 那条管的是**难度 1 的新号**；调其中一条时先认准自己动的是哪一侧。
 *   英雄基准取「普攻型四人组」（火枪 / 幻影刺客 / 卓尔游侠 / 冥界亚龙）——
 *   ⚠ 那 5 个技能型英雄（宙斯 / 水晶室女 / 莉娜 / 谜团 / 斧王）的输出有相当一部分在**技能**里，
 *     定标脚本只算普攻面板，所以对它们偏保守。
 *
 * ── 定标脚本（**2026-11 换过一次，别再拿旧结论**）──
 *   · 权威：`node tools/difficulty-curve/sim.mjs`（`--json=` → `chart.mjs` 出图表页）
 *     —— 它把**局外遗物 / 神器（击杀数商店）/ 阶段奖励倍率 / 「4 选 1 挑最好的那件」**
 *     四个乘区都算进去了，并且按「**难度档 × 成长档位**」两维打印。
 *   · `node tools/difficulty-curve/tune.mjs` 是**求解器**：直接回答"要让某个成长档打到 40 秒，
 *     血条倍率该给多少"（它也是难度阶梯开平方那五個底数的出处）。
 *   · ⚠ `tools/boss-balance/sim.mjs` **仍可跑**（它的口径是"某一档难度下 10 个英雄谁打不打得完
 *     150 秒"，是**英雄之间的横向公平**），但它**漏了上面四个乘区**，
 *     所以**不要再拿它定标** —— 它算出来的"基准玩家"比真玩家弱 20~50 倍。
 *
 * ── Boss 的基础值（`units.json#2006`，本表是乘在它上面的倍率）──
 *   HP **3000** · 护甲 **12** · 攻击 **60** · 攻击间隔 2.5s · 攻速 80。
 *   最终 Boss 的护甲还要 ×`FINAL_BOSS_ARMOR_MUL`(1.6) ⇒ 19.2 ⇒ **物理减伤 53.5%**
 *   ⇒ **物理有效血 = HP ÷ 0.465**。口径：
 *     墙钟 TTK = HP × 倍率 ÷ 物理系数 ÷ DPS ÷ 命中率(0.75)
 *     命中率 0.75 = Boss 会走位（BossAI 的 orbit / attack_stop 阶段）、会被小怪分流、弹道在飞。
 *
 * ── 实测（难度 100 · 十英雄中位 / 每格 4 局 · `sim.mjs`，±10%）──
 *
 *     | 轮次                        | 阶段 Boss#1 | #2   | #3   | 最终 Boss |
 *     |-----------------------------|-------------|------|------|-----------|
 *     | 最高成长 · 墙钟 TTK         | 43.3s       | 44.2s| 24.9s| **49.3s** |
 *     | 中位     · 墙钟 TTK         | 352s        | 245s | 78.8s| 118s      |
 *     | 最低成长 · 墙钟 TTK         | 4835s       | 4737s| 1420s| 1321s     |
 *     | 最高成长 · **被 Boss 打死** | 21s         | 23s  | 不死 | 不死      |
 *
 *   （"最低成长"在难度 100 是**故意的不可玩区**：那一档的服务对象是最高成长玩家；
 *     最低成长的"正正好"档位是难度 1，见 `docs/difficulty-curve/README.md` §2 判据 ①。）
 *   ⚠ 表里 **#1 / #2 两列是 2026-11 下调之前（×1 / ×1.6 那版）的读数**，现在这两只是 ×0.25 / ×0.8，
 *     所以高难度下它们的 TTK 也一起变短了（#3 与最终 Boss 那两列**未受影响**，仍以本表为准）。
 *
 * ── 改这里之前必须知道的三件事 ──
 *   ① **一条 40~60 秒的仗有一条硬预算：Boss 能打出的总伤害 ≈ 英雄一条血。**
 *      这也解释了"为什么攻击倍率小于血量倍率"：原来 5 秒就结束的仗，Boss 根本没机会
 *      打完它那点伤害 —— **把血量修好，"威胁"是自动回来的**，不需要靠抬攻击去补。
 *   ② **英雄的遗物护甲把 Boss 的普攻吃掉一大半**（最终 Boss 时刻中位 24 点 = 物理减伤 59%）。
 *      所以 Boss 的物理普攻**不是**威胁的有效旋钮，火球术那类**魔法伤害**才是
 *      （护甲不减它，只吃 35% 魔抗）。想加威胁优先加机制，别加倍率。
 *      ⚠ **2026-11 实测的缺口**：中位/最高成长在**低难度**（1~10 档）面对 Boss 是**不死**的
 *      —— 护甲 + 受伤减免 + 吸血把 Boss 的输出全吃掉了（见 `docs/difficulty-curve/README.md` §5）。
 *      也就是说"威胁"这件事**不能只修血条**，这是"攻击侧也要对位"那条提案的由来。
 *   ③ **英雄之间的 DPS 差 2.3 倍**（最终 Boss 时刻 279 ~ 649），任何单一血量都不可能让所有英雄都"正好 40 秒"。
 *      本表按**普攻四人组（火枪 / 幻影刺客 / 卓尔游侠 / 冥界亚龙）**定标：
 *      弱侧（谜团 / 水晶室女等垫底的五个）会打到 60~90 秒 —— Boss 阶段 150 秒限时**仍然够**，
 *      但已经没有余量了；强侧（卓尔游侠 / 火枪）**35 秒左右**。
 *      ⚠ 这里原先挂着一条"赏金猎人 `units.json#1002` 的 `atk = 200` 是异常值"（设计稿写 12、
 *      同级英雄都按 ×2 折算 ⇒ 应约 24）—— **2026-11 已修成 24**：他的最终 Boss TTK 从 **4s 回到 53s**，
 *      全表的 TTK 离散度同时从 **4~136s 收到 53~124s**（推导见 `docs/agent-notes/配表与数值口径.md`）。
 *      教训同样是这一条：**英雄侧的离群值不要用 Boss 血量去补**（补了就是把另外 9 个英雄一起搞崩）。
 *      ⚠ **2026-11 这条预警应验了，已按它执行**：用户报「难度 1 都打不过」，
 *      改的就是 `STAGE_BOSS_HP_MUL[0]`（×1 → ×0.25）与 `[1]`（×1.6 → ×0.8），
 *      攻击表跟着同一组数走，**别的一律没动**（阶段 3 / 最终 Boss / 难度底数 / 遗物全未碰）。
 *
 * @example
 * ```ts
 * import { bossStrengthMul } from '../common/BossStrengthConfig';
 * import { UnitKind } from '../common/EntityVisualConfig';
 *
 * // 在刷新点（Scene_Game_Stage.spawnBoss）拿到本次该乘的倍率
 * const mul = bossStrengthMul(kind, stage);   // 最终 Boss → { hp: 5.3, atk: 2.5, armor: 1.6 }
 * ```
 */

import { UnitKind } from './EntityVisualConfig';

/**
 * 阶段 Boss 的 **HP 倍率**（下标 = `spawnBoss(stage)` 收到的阶段号 - 1，即阶段 1/2/3 末那三只）。
 *
 * ⚠ **2026-11 用户口径「难度 1 我打不过，阶段 Boss 强度调低到 1/4」** ——
 *   阶段 1 **×1 → ×0.25**、阶段 2 **×1.6 → ×0.8**（= 用户给的两个数，血量与攻击**同一组**）；
 *   **阶段 3（×2.6）与最终 Boss 本轮不动**（用户原话「其他先不动」）。
 *   实测（难度 1 · 最低成长 · `sim.mjs`）：阶段 Boss#1 墙钟 TTK **49.4s → 12.4s**、
 *   #2 **47.6s → 23.8s**；反向"Boss 打死英雄"从 **73s / 81s → 330s / 136s**。
 *   ⚠ 改动后 #3 与 #1/#2 之间会出现一个**陡坎**（第 3 项仍是 ×2.6 = 7800 血）；
 *   要继续铺平就改本表第 3 项，**不要**回头去抬第 1/2 项。
 *
 * 为什么原先写的是递增的：玩家在这三个时刻的面板 DPS 是 119 → 176 → 323（×2.7），
 * 血量不跟着涨，后一只 Boss 就比前一只死得更快（实测墙钟 59s → 40s → 22s）。
 * 乘上原表后三只的墙钟 TTK 被拉成一条平线（59s → 63s → 58s）—— 那条口径服务的是
 * **高成长玩家的"收官战分量"**，而它把**低难度新号**那一侧顶到了刚好打不过，所以现在按难度分层让路。
 *
 * ⚠ 阶段 4 末刷出的是**最终 Boss**（`resolveBossKind(4) === FinalBoss`），不走这张表。
 */
export const STAGE_BOSS_HP_MUL: readonly number[] = [0.25, 0.8, 2.6];

/**
 * 阶段 Boss 的**攻击倍率**（与 HP 同下标）。
 *
 * 英雄血量在同样三个时刻是 764 → 1088 → 1454（×1.9），而**护甲是 3.5 → 9.1 → 16.0**
 * （物理减伤 17% → 35% → 49%）—— 所以攻击必须跟着涨一档，
 * 才能让"站着硬吃会死"在三个阶段里一样成立（见 `FINAL_BOSS_ATK_MUL` 的反推口径）。
 *
 * ⚠ **2026-11 与 HP 表同步下调**（用户口径「阶段 Boss 强度调低，阶段 1 → ×0.25、阶段 2 → ×0.8」）：
 *   攻击与血量**吃同一组数**（`1 → 0.25` / `1.3 → 0.8`），不是各算各的比值 ——
 *   用户给的是"这一阶段的强度倍率"一个数，两条轴都按它走。
 *   实际面板（`units.json#2006` 攻 60）：阶段 1 **60 → 15**、阶段 2 **78 → 48**、阶段 3 仍 96。
 *   ⚠ 这一条才是"低难度站着被打会不会死"的旋钮（护甲只削物理，见文件头口径 ②）。
 */
export const STAGE_BOSS_ATK_MUL: readonly number[] = [0.25, 0.8, 1.6];

/**
 * **最终 Boss** 的 HP 倍率：3000 → **15900**（`1.0583^(N-1)` 的难度曲线仍照乘）。
 *
 * 目标（用户口径 2026-11）= **最高成长 · 难度 100 · 最终 Boss = 30 秒定标 × 取 75% = 40 秒**。
 * 反推（真表真源码，10 英雄 × 每格 4 局，见 `docs/difficulty-curve/README.md`）：
 *   难度 100 的最终 Boss 血条倍率 = `6.5 × (40 ÷ 49.3) ≈ 5.3`，代回去实测 **十英雄中位 40.0s、
 *   普攻四人组 35s**（定标基准那一组在目标下沿，属于刻意的：强侧本来该更快）。
 *
 * ── 演化史（别照旧记忆恢复）──
 *   · 2026-11 从 ×5 抬到 ×6，再抬到 ×6.5 —— 当时的依据是 `tools/boss-balance/sim.mjs`，
 *     而那个脚本**漏了四个乘区**（局外遗物 / 神器 / 阶段奖励倍率 / 「4 选 1 挑最好的那件」），
 *     它算出来的"基准玩家"比真玩家弱 **20~50 倍** ⇒ 倍数抬了也没用（真账号依旧 2 秒打完）。
 *   · 2026-11 第二次：**难度阶梯整体开平方**（`DifficultyConfig` 的五个底数，
 *     "旧第 N 档 = 新第 2N 档"）之后，旧的**第 50 档**变成了新的**第 100 档**，
 *     于是这条倍率按新的定标点重新反推成 **×5.3**。
 *   · ⚠ 同一段历史里另加了 `FINAL_BOSS_ARMOR_MUL`（护甲 ×1.6）：**护甲只削物理**，
 *     正好对应用户口径里的"**几下就 A 死**"（A = 普攻 = 物理）；血量那一档负责所有伤害类型。
 *   · 剩下的"威胁"**不靠倍率**，由 **Boss 自己的技能**承担：
 *     `units.json`#2006 现在带 3 个技能（深渊火球 / 恐惧咆哮 / 深渊诅咒），
 *     而在此之前它们**一个都放不出来**（`skillId` 写的是字符串 "fireball"，
 *     而 `CastAbility` 要数字 id）—— 见 `battle/ai/BossAI.ts` 文件头。
 *
 * ⚠ **不要靠继续抬这两个数去"加难度"**：`tune.mjs` 会直接报出"要让某个成长档打到 40 秒、
 *   需要多少倍率"，而它对**最低成长**只有 ×0.2（第 100 档）—— 也就是说这条倍率每抬一点，
 *   都是在把弱侧往"打不完"推。要更凶就加机制（新技能 / 召唤 / 限时压力）。
 */
export const FINAL_BOSS_HP_MUL = 5.3;

/**
 * **最终 Boss** 的**护甲**倍率（2026-11 新增）：12 → **19.2**（物理减伤 41.9% → 53.5%）。
 *
 * ── 为什么是"倍率"而不是直接改 `units.json`#2006 的护甲 ──
 *   `units.json`#2006 **同时是阶段 Boss 的配置行**（`defaultConfig` 里
 *   `stageBossUnitId === finalBossUnitId === 2006`）。直接改表里的护甲会把**阶段 Boss 一起变硬** ——
 *   而阶段 Boss 是"每 4 分钟一次的小考"，玩家那时手上只有 7~12 件遗物（模拟实测：
 *   阶段 Boss#1 的中位墙钟 TTK 会从 74 秒涨到 116 秒）。把这一层放在**刷新点曲线**里，
 *   就能只作用于最终 Boss，与 `hp` / `atk` 两条倍率走同一条路、同一个文件。
 *
 * ⚠ 护甲对**魔法伤害无效**（`DamagePipeline.applyResistance` 按伤害类型分支），
 *   所以这条倍率单独拿出来说：它削的是普攻，不是"全能减伤"（那是属性 12）。
 */
export const FINAL_BOSS_ARMOR_MUL = 1.6;

/**
 * **最终 Boss** 的攻击倍率：60 → 150（每 3.13 秒一次）。
 *
 * 这条数不是"手感"调出来的，是**反推**出来的 —— 见文件头口径 ①：
 *   · 英雄在最终 Boss 时刻：血量中位 ≈ 1900、**遗物护甲中位 ≈ 24（物理减伤 59%）**；
 *   · 150 攻 → 48 原始 DPS → 扣掉护甲 ≈ 19.9 实收 DPS；
 *   · 60 秒的仗里实收 ≈ 1190（63% 血条），另有火球术（魔法伤害，护甲不减）≈ 390
 *     ⇒ 合计 ≈ 1580 ≈ **83% 血条**；扣掉「击杀回血 6/杀 × 1.57 杀/秒」的 ≈ 560
 *     ⇒ **整场净掉约半条血** —— "扛得住，但没有余量"，这就是 60 秒仗能给的威胁上限。
 *
 * ⚠ **再往上加就不是变强，而是变成"没有续航就必死"**：
 *   零护甲构筑（约两成局）在同一条数下 60 秒会掉 2880 点，直接打空一条血。
 *   要让 Boss 更凶，正确做法是加**机制**（更痛的主动技能 / 召唤 / 限时压力），
 *   不是把这个倍率继续往上抬 —— 抬它只会把"打不打得过"变成"抽没抽到护甲遗物"。
 */
export const FINAL_BOSS_ATK_MUL = 2.5;

/** 取倍率表里的第几档（越界一律夹到两端 —— 无尽模式的阶段号会一直涨） */
function pick(table: readonly number[], stage: number): number {
    if (!table.length) return 1;
    const n = Number.isFinite(stage) ? Math.floor(stage) : 1;
    const idx = Math.min(table.length - 1, Math.max(0, n - 1));
    return table[idx] ?? 1;
}

/** 一次刷新的强度倍率（`hp` = 最大生命 / `atk` = 攻击 / `armor` = 护甲，全部是倍率） */
export interface BossStrength {
    hp: number;
    atk: number;
    /** **护甲**倍率（2026-11 新增；1 = 不改）。只有最终 Boss 会拿到非 1 的值 */
    armor: number;
}

/**
 * **唯一入口**：这一次刷出来的 Boss 该乘多少。
 *
 * @param kind  本次刷新的表现类别（只有 `StageBoss` / `FinalBoss` 会拿到非 1 的结果）
 * @param stage `spawnBoss(stage)` 收到的阶段号（**调用时尚未 +1**，所以阶段 4 传进来的是 4）
 * @returns 倍率；非 Boss（普通/精英/经济 Boss 等）恒为 `{ hp: 1, atk: 1, armor: 1 }`
 */
export function bossStrengthMul(kind: UnitKind, stage: number): BossStrength {
    if (kind === UnitKind.FinalBoss) {
        return { hp: FINAL_BOSS_HP_MUL, atk: FINAL_BOSS_ATK_MUL, armor: FINAL_BOSS_ARMOR_MUL };
    }
    // 无尽模式每阶段都有 Boss（`ENDLESS_BOSS_EVERY_STAGES = 1`），阶段号会一直涨 →
    // `pick` 会把它夹在最后一档（×2.6），再叠上模式自己的 `stageHpMul`（×1.25/阶段）。
    if (kind === UnitKind.StageBoss) {
        return { hp: pick(STAGE_BOSS_HP_MUL, stage), atk: pick(STAGE_BOSS_ATK_MUL, stage), armor: 1 };
    }
    return { hp: 1, atk: 1, armor: 1 };
}

/**
 * 一句话描述这套曲线（「游戏规则说明」面板与开局日志用）——
 * 与 `GameRulesConfig` 的 `bossHpMul(difficulty)` 那句**同源**：改上面的常量，文案跟着变。
 */
export function describeBossStrength(): string {
    const stage = STAGE_BOSS_HP_MUL.map((v, i) => `×${v}`).join(' / ');
    const atk = STAGE_BOSS_ATK_MUL.map((v) => `×${v}`).join(' / ');
    return `阶段 Boss（阶段 1 / 2 / 3 末）血量 ${stage}、攻击 ${atk}；`
        + `最终 Boss 血量 ×${FINAL_BOSS_HP_MUL}、攻击 ×${FINAL_BOSS_ATK_MUL}、护甲 ×${FINAL_BOSS_ARMOR_MUL}`;
}
