/**
 * ============================================================
 * TargetSelectConfig —— 「点选索敌」（点击怪物切换普攻目标）的**唯一数值真源**
 * ============================================================
 *
 * 这条交互只有两件事，数值都收在这里，别写进场景或组件里：
 *   ① `TAP_SELECT` —— **点得中吗**：判定半径、拖拽容差、输入区尺寸；
 *   ② `TARGET_MARK` —— **看得出来打谁吗**：选中标记的配色与画法。
 *
 * ---- 为什么点选要"垫一圈"（hitPadPx）----
 *   占位美术阶段所有怪共用 `prefabs/unit/monsters/one`，本体只有 **20×20px**（半径 10，
 *   Boss 靠类别缩放 ×1.5/×2 → 15/20），在 750×1334 的竖屏上是一个手指尖盖不满的小点。
 *   按本体判半径 → 玩家"明明点到怪了却没反应"，这条交互直接被读成坏了。
 *   所以判定半径 = `实体半径 + hitPadPx`，并且**不小于 minHitRadiusPx**。
 *
 * ---- 为什么拖拽不算点选（slopPx）----
 *   手指按在怪身上再划走（看战场 / 顺手蹭一下）不该改目标 —— 判据是"按下点到抬起点的位移"。
 *   这与 UI 里"点击 vs 滑动"的通用容差口径一致（本项目没有滚动列表，取一个偏紧的值即可）。
 *
 * ---- 配色口径（与 `docs/美术风格预设.md` 的 token 对齐）----
 *   风格预设是**双强调色**：`青绿 = 系统 / 可操作 / 选中`，`暗红 = 英雄与人`。
 *   选中环是"玩家选中的那个" → 取 `c-accent-ring #6FA9A7`（**只描边**，与卡片选中态同一支）。
 *   它不参与打击反馈的"颜色只回答打谁"（口径见 `docs/打击反馈设计.md` §2）：那是**印痕**的规则，
 *   印痕是"刚发生了什么"，本层是"接下来打谁" —— 一个是事件、一个是状态，两者不该混用一套色。
 *   形状上也刻意与既有圆环区分：英雄射程圈是**淡青灰 `#C0CCD1` 单环**（见预制件 `hero/range`），
 *   这里用"环 + 四角括号"的组合，读作「框选/锁定」而不是「范围」。
 */

/** 点选（触摸）判定参数 */
export const TAP_SELECT = {
    /**
     * 点选判定的**额外半径**（像素）：判定半径 = 实体半径（`Entity.collisionRadius`，已含体型缩放）+ 它。
     *
     * 26px ≈ 本体半径的 2.6 倍 —— 相邻两只哥布林（中心距 ~20~30px）之间点下去仍能选中更近的那只，
     * 而不会出现"点两下选中的是同一只"。
     */
    hitPadPx: 26,

    /**
     * 点选判定的**最小半径**（像素）：`collisionRadius` 缺失或为 0 时用它兜底。
     *
     * 没有它的话，将来某只单位的半径配成 0（或占位美术换掉）就会静默变成"永远点不中"。
     */
    minHitRadiusPx: 34,

    /** 点按容差（像素）：按下点与抬起点的位移超过它就当作拖拽，不触发点选 */
    slopPx: 20,

    /**
     * 输入区节点的 UITransform 覆盖尺寸（像素）。
     *
     * 必须**大于整个可见战场**（屏幕 750×1334，怪物从 650~800 的外圈进场）：输入区就是这块矩形，
     * 点不到矩形里的东西就等于没有这条交互。取值与 `HitVfxLayer` 的同名常量同量级。
     */
    coverSize: 4000,
};

/** 选中标记（"现在打的是它"）的画法 */
export const TARGET_MARK = {
    /** `c-accent-ring #6FA9A7`：青绿族里**专用于选中描边**的那一支（风格预设 §1.1） */
    color: 0x6fa9a7,

    /**
     * 标记的不透明度（0~255）。
     *
     * 压满会读成"UI 边框贴在怪身上"（浅底上青绿本来就比墨色跳），而这是个**常驻**标记，
     * 比印痕那种一瞬即逝的图形更容易看腻 —— 留一点透明度让它退到实体后面。
     */
    alpha: 210,

    /** 线宽（像素，环与括号共用 —— 同一线宽就能一次 stroke 画完，恒 1 次 draw call） */
    lineWidthPx: 2,

    /** 环半径 = 实体半径 + 它（像素）：贴着本体外缘留一圈缝，不盖住怪 */
    ringPadPx: 7,

    /** 环的最小半径（像素）：小怪（半径 10）加完也只有 17，再小就画不成环 */
    ringMinRadiusPx: 17,

    /**
     * 四角括号：臂长 / 离环的距离（像素）。
     *
     * 括号**永远朝屏幕四角、不随怪旋转**：旋转的括号在浅底上会读成"乱码"，而怪本来就一直在动。
     * 四角 = 框选语义（与"范围圈"区分开），臂长 7px 在 20px 的怪身上正好看得出是个角。
     */
    bracketArmPx: 7,
    bracketGapPx: 4,
};
