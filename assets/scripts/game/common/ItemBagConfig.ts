/**
 * ============================================================
 * ItemBagConfig —— **局内掉落 Buff 背包**的唯一数值真源（纯 TS，无 cc 依赖）
 * ============================================================
 *
 * 只管三件事：几个格子、每次 Boss 掉几件、飘字用不用。它不知道谁在读，也不碰任何节点/存档。
 *
 * ── 谁在读 ──
 *   ① `battle/ItemBag.ts`（格子数、每次掉落件数）
 *   ② HUD 背包组件（`cmps/item_bag/*`：**格数必须读这里，不许自己写 6** —— 写死了改一处漏一处；
 *      展开时长 / 双击窗口 / 飞入时长也在本文件下半段）
 *
 * ── 为什么格数是 TS 常量而不是 `shop_constants` 的一行 ──
 *   HUD 上就是 6 个节点，这个数是**结构**不是**平衡参数**（预制件里已经烤死了 6 个格子）。
 *   项目的先例同 `StageTimingConfig.STAGE_COUNT` / `BattleSpeedConfig`：
 *   结构常量放 TS，平衡参数放配表。
 *
 * ⚠ 改这个数要**同时**改 HUD 预制件（多/少一个格子），否则会出现"第 7 格装得下但看不见"。
 */

/** 局内小背包格数（= HUD 上那排格子的个数）。用户口径 2026-11：**只有 6 个格子** */
export const ITEM_BAG_SLOT_COUNT = 6;

/** 每次「阶段 Boss 阵亡」掉几件（用户口径：每个阶段 Boss 掉 1 件） */
export const BATTLE_ITEM_DROP_PER_BOSS = 1;

/** 空格子的槽位值（`slots` 数组用 `0` 表示空格，与 `BuffShop.slots` 的表达方式一致） */
export const EMPTY_SLOT = 0;

/* ===================================================================
 * HUD 表现参数（只有 `cmps/item_bag/*` 读；**组件里不许写死这些数**）
 * =================================================================== */

/**
 * 展开 / 收起的滑出时长（秒）。
 * 短是刻意的：这是"点一下看看背包里有什么"的高频小动作，动画超过 0.25s 就会拖慢操作。
 */
export const ITEM_BAG_EXPAND_SECONDS = 0.16;

/**
 * **双击**判定窗口（秒）：同一个格子上两次点击间隔小于它就当成"双击 = 使用"。
 * ⚠ 单击是"看描述"，所以单击**不等待**这个窗口（先弹描述，够快就升级成使用）——
 *   若要"等 300ms 确认不是双击再弹描述"，点一下会明显发涩。
 */
export const ITEM_BAG_DOUBLE_CLICK_SECONDS = 0.3;

/** 掉落图标飞向背包的时长（秒）与弧线拱起高度（像素，同打击反馈的奖励飞入口径） */
export const ITEM_BAG_FLY_SECONDS = 0.42;
export const ITEM_BAG_FLY_ARC = 80;

/** 飞行中的道具块边长（像素）——比格子（72）小一圈，落格时才有"收进去"的读法 */
export const ITEM_BAG_FLY_SIZE = 64;

/** 飘字提示挂在背包按钮之上多少像素（同技能栏飘字的写法） */
export const ITEM_BAG_FLOAT_OFFSET_Y = 76;
